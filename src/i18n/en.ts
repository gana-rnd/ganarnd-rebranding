// 구조적 타입 — 모든 문자열은 string으로 넓혀서 다른 언어 번역을 허용
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? U extends { t: string; d: string }
      ? { t: string; d: string }[]
      : string[]
    : { [P in keyof T]: Widen<T[P]> };

